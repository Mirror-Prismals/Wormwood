BANNER = '// Generated by Procedures/Shaders/generate_workstation.py. Edit workstation.shared.glsl.\n'


def wgsl(source):
    types = {'float': 'f32', 'int': 'i32', 'bool': 'bool',
             'vec2': 'vec2<f32>', 'vec3': 'vec3<f32>', 'vec4': 'vec4<f32>',
             'ivec3': 'vec3<i32>', 'GemHit': 'GemHit', 'GemRay': 'GemRay'}
    def struct(match):
        fields = []
        for field in match[2].split(';'):
            if field.strip():
                kind, name = field.strip().split()
                fields.append(f'{name}:{types[kind]}')
        return 'struct ' + match[1] + ' {' + ','.join(fields) + '};'
    source = re.sub(r'struct (\w+)\s*\{([^}]+)\};', struct, source)
    names = '|'.join(types)
    def function(match):
        result, name, arguments = match.groups()
        params = []
        for arg in arguments.split(','):
            if arg.strip():
                kind, parameter = arg.strip().split()
                params.append(parameter + ':' + types[kind])
        return 'fn ' + name + '(' + ','.join(params) + ')->' + types[result] + ' {'
    source = re.sub(r'\b(' + names + r') (\w+)\(([^()]*)\)\s*\{', function, source)
    source = re.sub(r'\b(' + names + r') (\w+)\[(\d+)\];',
                    lambda m: 'var ' + m[2] + ':array<' + types[m[1]] + ',' + m[3] + '>;', source)
    source = re.sub(r'\b(' + names + r') (\w+)\s*=',
                    lambda m: 'var ' + m[2] + ':' + types[m[1]] + '=', source)
    for kind in ('ivec3', 'vec4', 'vec3', 'vec2', 'float', 'int'):
        source = re.sub(r'\b' + kind + r'\(', types[kind] + '(', source)
    # The kernel deliberately uses braces and explicit vector scalar broadcasts,
    # so no control-flow or arithmetic rewrites can alter its numerical meaning.
    return source


wgsl_vertex = '''struct SceneVertex {position:vec4<f32>,data:vec4<f32>};
struct Appearance {vertices:array<SceneVertex>};
@group(0) @binding(0) var<storage,read> appearance:Appearance;
struct WorkstationData {rows:array<vec4<f32>>};
@group(0) @binding(1) var<storage,read> workstationData:WorkstationData;
fn gemRow(index:i32)->vec4<f32>{return workstationData.rows[u32(index)];}
struct VertexOutput {@builtin(position) position:vec4<f32>,@location(0) screen:vec2<f32>,@location(1) cameraData:vec4<f32>};
@vertex fn vs_main(@builtin(vertex_index) index:u32)->VertexOutput {
 var o:VertexOutput;o.position=appearance.vertices[index].position;
 o.screen=o.position.xy/o.position.w;o.cameraData=appearance.vertices[index].data;return o;
}
'''
(ROOT / 'workstation.wgsl').write_text(BANNER + wgsl_vertex + wgsl(SOURCE) + (ROOT/'theatre_camera.wgsl').read_text() + '''
@fragment fn fs_main(input:VertexOutput)->@location(0) vec4<f32>{let tf=max(length(dpdx(input.cameraData.xy)),length(dpdy(input.cameraData.xy)));if((input.cameraData.w>=112. && input.cameraData.w<=116. && input.cameraData.w!=114.)){return exteriorSurface(input.cameraData,max(length(dpdx(input.cameraData.xyz)),length(dpdy(input.cameraData.xyz))));}if(input.cameraData.w>=117. && input.cameraData.w<=120.){return carpetSurface(input.cameraData,max(length(dpdx(input.cameraData.xyz)),length(dpdy(input.cameraData.xyz))));}if(input.cameraData.w>=106.0 && input.cameraData.w<=111.0){return tableSurface(input.cameraData,tf);}if(input.cameraData.w>=99.5 && (input.cameraData.w<=104.5 || input.cameraData.w==114.)){return theatreSample(input.cameraData);}if(input.cameraData.w>89.5){return vec4<f32>(input.cameraData.xyz,1.0);}if(gemRow(9).z>0.5&&gemBackdropVisible(input.screen)){discard;}return workstationShade(input.screen);}
''')

vertex_body = '''void main(){gl_Position=position;screen=position.xy/position.w;cameraData=vertexData;gl_Position.z=2.0*position.z-position.w;}\n'''
for name, version, precision in [('gl', '#version 330 core\n', ''),
                                 ('ios', '#version 300 es\n', 'precision highp float;precision highp int;\n')]:
    (ROOT / ('workstation.' + name + '.vert')).write_text(version + BANNER + precision + '''
layout(location=0) in vec4 position;
layout(location=1) in vec4 vertexData;
out vec2 screen;
out vec4 cameraData;
''' + vertex_body)
    (ROOT / ('workstation.' + name + '.frag')).write_text(version + BANNER + precision + '''
in vec2 screen;in vec4 cameraData;out vec4 pixel;
uniform highp sampler2D workstationData;
vec4 gemRow(int index){return texelFetch(workstationData,ivec2(index%256,index/256),0);}
''' + SOURCE + (ROOT/'theatre_camera.glsl').read_text() + '\nvoid main(){float tf=max(length(dFdx(cameraData.xy)),length(dFdy(cameraData.xy)));if((cameraData.w>=112. && cameraData.w<=116. && cameraData.w!=114.)){pixel=exteriorSurface(cameraData,max(length(dFdx(cameraData.xyz)),length(dFdy(cameraData.xyz))));return;}if(cameraData.w>=117. && cameraData.w<=120.){pixel=carpetSurface(cameraData,max(length(dFdx(cameraData.xyz)),length(dFdy(cameraData.xyz))));return;}if(cameraData.w>=106.0 && cameraData.w<=111.0){pixel=tableSurface(cameraData,tf);return;}if(cameraData.w>=99.5 && (cameraData.w<=104.5 || cameraData.w==114.)){pixel=theatreSample(cameraData);return;}if(cameraData.w>89.5){pixel=vec4(cameraData.xyz,1.0);return;}if(gemRow(9).z>0.5&&gemBackdropVisible(screen)){discard;}pixel=workstationShade(screen);}\n')

